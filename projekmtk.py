print("=" * 60)

jawaban = pd.DataFrame({
    f"P{i+1}": df[p].value_counts()
    for i, p in enumerate(k[9:23])
}).T

jawaban = jawaban[
    ["Benar", "Tidak Tahu", "Salah"]
].fillna(0)

jawaban.plot(
    kind="barh",
    stacked=True,
    color=[
        "#548235",
        "#BFBFBF",
        "#C00000"
    ],
    figsize=(7, 5)
)

plt.title(
    "Jawaban per Pernyataan Pengetahuan"
)

plt.xlabel("Jumlah responden")

plt.gca().invert_yaxis()

