import pandas as pd
import matplotlib.pyplot as plt


# ============================================================
# 1. BACA DATA
# ============================================================

print("\n" + "=" * 60)
print("1. BACA DATA")
print("=" * 60)

df = pd.read_excel("3TIB_05_PemahamanPaliatif.xlsx")

print("Jumlah responden :", len(df))
print("Jumlah kolom     :", len(df.columns))


# ============================================================
# 2. RENAME KOLOM
# ============================================================

print("\n" + "=" * 60)
print("2. RENAME KOLOM")
print("=" * 60)

k = df.columns

df = df.rename(columns={
    k[2]: "Usia",
    k[3]: "Pendidikan",
    k[4]: "Status",
    k[5]: "Kerabat_kanker",
    k[6]: "Pernah_merawat",
    k[7]: "Pernah_dengar",
    k[8]: "Pemahaman_diri",
    k[33]: "Cemas_merawat",
    k[34]: "Penting_edukasi",
    k[35]: "Animasi_membantu",
    k[36]: "Nyaman_visual"
})

k = df.columns

print("Kolom berhasil diubah.")


# ============================================================
# 3. MENGHITUNG SKOR PENGETAHUAN
# ============================================================

print("\n" + "=" * 60)
print("3. SKOR PENGETAHUAN")
print("=" * 60)

# Kolom 9 sampai 22 = 14 pertanyaan pengetahuan
# Jawaban "Benar" = 1
# Jawaban selain "Benar" = 0

df["Skor_pengetahuan"] = (
    (df[k[9:23]] == "Benar").sum(axis=1)
)

print("Jumlah pertanyaan pengetahuan :", len(k[9:23]))
print("Skor maksimum                 :", 14)
print("Kolom hasil                   : Skor_pengetahuan")


# ============================================================
# 4. MENGHITUNG SKOR KHAWATIR
# ============================================================

print("\n" + "=" * 60)
print("4. SKOR KHAWATIR")
print("=" * 60)

# Kolom 23 sampai 27 = 5 pertanyaan
df["Skor_khawatir"] = df[k[23:28]].sum(axis=1)

print("Jumlah pertanyaan :", len(k[23:28]))
print("Skor minimum      : 5")
print("Skor maksimum      : 25")
print("Kolom hasil       : Skor_khawatir")


# ============================================================
# 5. MENGHITUNG SKOR KESIAPAN
# ============================================================

print("\n" + "=" * 60)
print("5. SKOR KESIAPAN")
print("=" * 60)

# Kolom 28 sampai 32 = 5 pertanyaan
df["Skor_kesiapan"] = df[k[28:33]].sum(axis=1)

print("Jumlah pertanyaan :", len(k[28:33]))
print("Skor minimum      : 5")
print("Skor maksimum      : 25")
print("Kolom hasil       : Skor_kesiapan")


# ============================================================
# 6. MENAMPILKAN HASIL SKOR
# ============================================================

print("\n" + "=" * 60)
print("6. HASIL PERHITUNGAN SKOR")
print("=" * 60)

print(
    df[
        [
            "Skor_pengetahuan",
            "Skor_khawatir",
            "Skor_kesiapan"
        ]
    ].head(10)
)


# ============================================================
# 7. STATISTIK DESKRIPTIF
# ============================================================

print("\n" + "=" * 60)
print("7. STATISTIK DESKRIPTIF")
print("=" * 60)

kolom = [
    "Usia",
    "Pemahaman_diri",
    "Skor_pengetahuan",
    "Skor_khawatir",
    "Skor_kesiapan",
    "Cemas_merawat",
    "Penting_edukasi",
    "Animasi_membantu",
    "Nyaman_visual"
]

hasil = pd.DataFrame({
    "N": df[kolom].count(),
    "Mean": df[kolom].mean(),
    "Median": df[kolom].median(),
    "Modus": df[kolom].mode().iloc[0],
    "SD": df[kolom].std(),
    "Min": df[kolom].min(),
    "Maks": df[kolom].max(),
    "Q1": df[kolom].quantile(0.25),
    "Q3": df[kolom].quantile(0.75),
    "Skewness": df[kolom].skew()
}).round(2)

print(hasil)


# ============================================================
# 8. FREKUENSI VARIABEL KATEGORIK
# ============================================================

print("\n" + "=" * 60)
print("8. FREKUENSI VARIABEL KATEGORIK")
print("=" * 60)

for kol in [
    "Pendidikan",
    "Status",
    "Pernah_merawat",
    "Pernah_dengar"
]:

    print("\n---", kol, "---")

    frekuensi = pd.DataFrame({
        "N": df[kol].value_counts(),
        "%": df[kol]
            .value_counts(normalize=True)
            .mul(100)
            .round(1)
    })

    print(frekuensi)


# ============================================================
# 9. KELOMPOK USIA
# ============================================================

print("\n" + "=" * 60)
print("9. KELOMPOK USIA")
print("=" * 60)

df["Kelompok_usia"] = pd.cut(
    df["Usia"],
    [0, 17, 25, 35, 45, 100],
    labels=[
        "<18",
        "18-25",
        "26-35",
        "36-45",
        ">45"
    ]
)

print(df["Kelompok_usia"].value_counts().sort_index())


# ============================================================
# 10. KATEGORI SKOR PENGETAHUAN
# ============================================================

