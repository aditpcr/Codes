# ============================================================
# 18. HISTOGRAM SKOR
# ============================================================

print("\n" + "=" * 60)
print("18. MEMBUAT HISTOGRAM SKOR")
print("=" * 60)

bins = range(0, 27, 2)

for kol, judul in [
    ("Skor_pengetahuan", "Skor Pengetahuan"),
    ("Skor_khawatir", "Skor Kekhawatiran"),
    ("Skor_kesiapan", "Skor Kesiapan")
]:

    df[kol].plot(
        kind="hist",
        bins=bins,
        color="#2E75B6",
        edgecolor="white"
    )

    plt.axvline(
        df[kol].mean(),
        color="red",
        linestyle="--",
        label="Mean"
    )

    plt.title("Histogram " + judul)
    plt.xlabel(judul)
    plt.ylabel("Frekuensi")
    plt.legend()

    plt.savefig(
        "g_hist_" + kol + ".png",
        dpi=150,
        bbox_inches="tight"
    )

    plt.show()
    plt.clf()


